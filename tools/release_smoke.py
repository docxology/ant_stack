class SmokeFailure(RuntimeError):
    def __init__(self, message: str, status: int = 1):
        super().__init__(message)
        self.status = status if 0 < status < 256 else 1


def require(condition, message):
    if not condition:
        raise SmokeFailure(message)


def identity(path):
    require(path.is_file() and not path.is_symlink(), f"Missing ordinary file: {path}")
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return {"sha256": digest.hexdigest(), "bytes": path.stat().st_size}


def ordinary(path):
    path = Path(os.path.abspath(path))
    require(not any(p.is_symlink() for p in (path, *path.parents)), f"Symlink path: {path}")
    return path


def relative_file(root, name):
    require(isinstance(name, str) and bool(name), "Artifact path must be a nonempty string")
    posix = PurePosixPath(name)
    require(not posix.is_absolute() and ".." not in posix.parts and "\\" not in name,
            f"Nonportable or escaping artifact path: {name}")
    result = ordinary(root / name)
    require(result.is_relative_to(root) and result != root, f"Escaping artifact: {name}")
    return result


def load_json(path):
    def bad_constant(value):
        raise SmokeFailure(f"Nonfinite JSON value in {path}: {value}")
    return json.loads(path.read_text(encoding="utf-8"), parse_constant=bad_constant)


def save_json(path, data):
    path.write_text(json.dumps(data, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")


